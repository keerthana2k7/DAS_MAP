// Helper to calculate total count
export function getTotalTopicsCount(categories: Category[] = initialRoadmapData): number {
  return categories.reduce(
    (acc, cat) => acc + cat.subcategories.reduce((sAcc, sub) => sAcc + sub.topics.length, 0),
    0
  );
}

// Flat map of all topics
export function getAllTopicsFlat(categories: Category[] = initialRoadmapData): { topic: Topic; category: Category; subcategory: Subcategory }[] {
  const result: { topic: Topic; category: Category; subcategory: Subcategory }[] = [];
  categories.forEach((category) => {
    category.subcategories.forEach((subcategory) => {
      subcategory.topics.forEach((topic) => {
        result.push({ topic, category, subcategory });
      });
    });
  });
  return result;
}
