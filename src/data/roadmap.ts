import { Category, Subcategory, Topic } from '../types/roadmap';

function createTopic(
  id: string,
  subcategoryId: string,
  name: string,
  order: number,
  isDsa = false
): Topic {
  return {
    id,
    subcategoryId,
    name,
    status: 'NOT_STARTED',
    confidence: 1,
    totalStudyMinutes: 0,
    lastStudiedAt: null,
    completedAt: null,
    revisionCount: 0,
    nextRevisionDate: null,
    notes: '',
    resources: [],
    problems: isDsa ? [] : undefined,
    order,
  };
}

